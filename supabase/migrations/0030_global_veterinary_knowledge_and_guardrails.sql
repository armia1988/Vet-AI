create table if not exists public.disease_source_refs (
  id uuid primary key default gen_random_uuid(),
  disease_id uuid not null references public.disease_catalog(id) on delete cascade,
  source_org text not null,
  jurisdiction text not null default 'global',
  source_title text,
  source_url text not null,
  evidence_scope text[] not null default '{}',
  source_reviewed_at date,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (disease_id, source_url)
);
alter table public.disease_source_refs enable row level security;
drop policy if exists "authenticated can read disease source refs" on public.disease_source_refs;
create policy "authenticated can read disease source refs" on public.disease_source_refs for select to authenticated using (true);
grant select on public.disease_source_refs to authenticated;

create table if not exists public.disease_aliases (
  id bigint generated by default as identity primary key,
  disease_id uuid not null references public.disease_catalog(id) on delete cascade,
  alias text not null,
  language_code text not null default 'en',
  source_org text,
  source_url text,
  created_at timestamptz not null default now(),
  unique (disease_id, alias, language_code)
);
alter table public.disease_aliases enable row level security;
drop policy if exists "authenticated can read disease aliases" on public.disease_aliases;
create policy "authenticated can read disease aliases" on public.disease_aliases for select to authenticated using (true);
grant select on public.disease_aliases to authenticated;

create table if not exists public.knowledge_sync_runs (
  id uuid primary key default gen_random_uuid(),
  source_org text not null,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  status text not null default 'running' check (status in ('running','success','partial','failed')),
  indexed_count integer not null default 0,
  reviewed_count integer not null default 0,
  error_summary text
);
alter table public.knowledge_sync_runs enable row level security;

create table if not exists public.voice_provider_events (
  id bigint generated by default as identity primary key,
  user_id uuid,
  requested_language text,
  provider text not null,
  model_or_voice text,
  outcome text not null check (outcome in ('success','failure','timeout','not_configured')),
